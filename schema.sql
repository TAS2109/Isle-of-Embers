CREATE TABLE IF NOT EXISTS ranks(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL, assets INTEGER NOT NULL, score INTEGER NOT NULL,
  years INTEGER NOT NULL, pop INTEGER NOT NULL, ip TEXT, ts INTEGER NOT NULL, daily TEXT
);
CREATE INDEX IF NOT EXISTS i_assets ON ranks(assets DESC);
CREATE INDEX IF NOT EXISTS i_score ON ranks(score DESC);
CREATE INDEX IF NOT EXISTS i_ip ON ranks(ip,ts);
CREATE INDEX IF NOT EXISTS i_daily ON ranks(daily,assets DESC);
